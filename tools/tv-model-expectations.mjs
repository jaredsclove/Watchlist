// Prints a self-check SQL script (for db/test/_prelude.sql) holding the
// JavaScript reference's answers (tests/tv-model-reference.js), so the database
// model can be compared on a Supabase test project, where this repo's Node
// tooling can't connect directly:
//   * every migrated show in the backup: status, skipped seasons, up next;
//   * every shared case: up next, Watching anchor, compatibility values.
// Usage: node tools/tv-model-expectations.mjs <backup.json> > expectations.sql
import fs from 'fs';
import path from 'path';
import { createRequire } from 'module';
import { fileURLToPath } from 'url';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const M = require(path.join(ROOT, 'tests/tv-model-reference.js'));
const CASES = JSON.parse(fs.readFileSync(path.join(ROOT, 'tests/fixtures/tv-model-cases.json'), 'utf8'));
const backup = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
const q = v => v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`;

// ── Migrated shows ───────────────────────────────────────────────────────────
const groups = M.groupShows(backup.tables.watchlist_items);
const exp = [];
for (const seasons of groups.values()) {
  const m = M.migrateShow(seasons);
  const flagged = seasons.map(s => ({ ...s, skipped: m.skippedIds.has(s.id) }));
  const next = M.upNext(flagged);
  const first = seasons[0];
  exp.push(`(${q(first.collection)}, ${first.tmdb_id ?? 'null'}, ${first.tmdb_id == null ? q(M.showKeyOf(first)) : 'null'}, ${q(m.status)}, ` +
    `${q(flagged.filter(s => s.skipped).map(s => s.item_key).sort().join(','))}, ${q(next ? next.item_key : null)})`);
}
console.log(`-- Generated by tools/tv-model-expectations.mjs from ${path.basename(process.argv[2])}: ${exp.length} shows.
select pg_temp.t('model vs reference: every migrated show (status, skipped seasons, up next)', $b$ do $$
declare v_missing int; v_extra int; v_bad text;
begin
  create temp table _exp (collection text, tmdb_id int, show_key text, status text, skipped_keys text, up_next_key text) on commit drop;
  insert into _exp values
    ${exp.join(',\n    ')};
  create temp table _got on commit drop as
  select s.collection, s.tmdb_id, s.show_key, s.status,
    (select coalesce(string_agg(w.item_key, ',' order by w.item_key collate "C"), '') from public.watchlist_items w where w.show_id = s.id and w.skipped) as skipped_keys,
    (select w.item_key from public.watchlist_items w where w.id = private.tv_up_next(s.id)) as up_next_key
  from public.tv_shows s;
  select count(*) into v_missing from _exp e where not exists (select 1 from _got g where g.collection = e.collection
    and (case when e.tmdb_id is not null then g.tmdb_id = e.tmdb_id else g.tmdb_id is null and g.show_key = e.show_key end));
  select count(*) into v_extra from _got g where not exists (select 1 from _exp e where g.collection = e.collection
    and (case when e.tmdb_id is not null then g.tmdb_id = e.tmdb_id else g.tmdb_id is null and g.show_key = e.show_key end));
  select string_agg(format('%s/%s: %s vs %s', e.collection, coalesce(e.tmdb_id::text, e.show_key), row(e.status, e.skipped_keys, e.up_next_key), row(g.status, g.skipped_keys, g.up_next_key)), '; ')
    into v_bad from _exp e join _got g on g.collection = e.collection
      and (case when e.tmdb_id is not null then g.tmdb_id = e.tmdb_id else g.tmdb_id is null and g.show_key = e.show_key end)
    where (e.status, e.skipped_keys, e.up_next_key) is distinct from (g.status, g.skipped_keys collate "C", g.up_next_key);
  if v_missing + v_extra > 0 or v_bad is not null then
    raise exception 'missing %, extra %, differing: %', v_missing, v_extra, left(coalesce(v_bad, '-'), 1500);
  end if;
end $$ $b$);`);

// ── Shared cases ─────────────────────────────────────────────────────────────
const STATUSES = ['confirmed', 'highpriority', 'watching', 'complete', 'pending', 'maybe', 'skipped'];
let i = 0;
const blocks = [];
for (const c of CASES.upNext) {
  const seasons = M.caseSeasons(c.seasons, CASES.today);
  const tmdb = 990000000 + (++i);
  const legacy = seasons[0].media_type == null;
  const ins = seasons.map(r => `(${q(r.collection)}, ${q(`zz case ${i}|${r.id.toLowerCase()}`)}, ${q('ZZ Case ' + i)}, ${q(r.season)}, ${r.season_number ?? 'null'}, ` +
    `${q(r.media_type)}, ${legacy ? 'null' : tmdb}, ${q(r.display_date)}, ${q(r.date_sort)}, ${r.watched}, ${r.skipped}, v_show)`).join(',\n      ');
  const up = M.upNext(seasons), anchor = M.watchingAnchor(seasons);
  const key = id => id == null ? 'null' : q(`zz case ${i}|${id.toLowerCase()}`);
  const proj = STATUSES.map(st => {
    const p = M.projectLegacyStatus(st, seasons);
    const want = seasons.map(r => `${r.id.toLowerCase()}:${p.get(r.id)}`).sort().join(',');
    return `  update public.tv_shows set status = '${st}' where id = v_show; perform private.tv_project_legacy_status(v_show);
  select string_agg(split_part(item_key, '|', 2) || ':' || status, ',' order by split_part(item_key, '|', 2) collate "C") into v_got from public.watchlist_items where show_id = v_show;
  if v_got is distinct from ${q(want)} then raise exception 'projection ${st}: %', v_got; end if;`;
  }).join('\n');
  blocks.push(`select pg_temp.t(${q('model vs reference case: ' + c.name)}, $b$ do $$
declare v_show uuid; v_got text;
begin
  insert into public.tv_shows (collection, title, show_key, tmdb_id) values (${q(seasons[0].collection)}, ${q('ZZ Case ' + i)}, ${q('zz case ' + i)}, ${legacy ? 'null' : tmdb}) returning id into v_show;
  insert into public.watchlist_items (collection, item_key, title, season, season_number, media_type, tmdb_id, display_date, date_sort, watched, skipped, show_id) values
      ${ins};
  select item_key into v_got from public.watchlist_items where id = private.tv_up_next(v_show);
  if v_got is distinct from ${key(up ? up.id : null)} then raise exception 'up next %', v_got; end if;
  select item_key into v_got from public.watchlist_items where id = private.tv_watching_anchor(v_show);
  if v_got is distinct from ${key(anchor ? anchor.id : null)} then raise exception 'anchor %', v_got; end if;
${proj}
end $$ $b$);`);
}
console.log(blocks.join('\n'));
console.log(`select json_agg(json_build_object('check', name, 'ok', ok, 'detail', detail) order by seq)::text as results,
       count(*) filter (where ok) || '/' || count(*) as passed
from _t;`);
